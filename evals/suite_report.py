#!/usr/bin/env python3
"""V4: per-category weakness report for the 80-prompt suite (no model calls).

  python3 evals/suite_report.py --out evals/results/suite-weakness.md
"""
from __future__ import annotations

import argparse
import json
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def current_card_sha() -> str:
    import hashlib
    return hashlib.sha256((ROOT / "hooks/core-card.md").read_bytes()).hexdigest()[:12]


def load() -> dict:
    # Only single-sample suite runs; brainres rows only from the current card (ablation runs use other cards, K1 fix).
    rows = []
    sha = current_card_sha()
    for p in sorted((ROOT / "evals/results").glob("*/summary.json")):
        d = json.loads(p.read_text())
        if d.get("prompt_set") == "suite.jsonl" and d.get("samples", 1) == 1:
            rows += [r for r in d["rows"] if not r.get("tool_markup")
                     and (r["condition"] == "baseline" or (r["condition"] == "brainres" and d.get("card_sha") == sha))]
    pairs = defaultdict(dict)
    for r in rows:
        pairs[r["id"]][r["condition"]] = r
    return {i: v for i, v in pairs.items() if "baseline" in v and "brainres" in v}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    a = ap.parse_args()
    P = load()
    lines = ["# Suite weakness report (V4)", "",
             f"Generated by `evals/suite_report.py` from {len(P)} valid baseline/brainres pairs (Sonnet, card proxy, 1 sample each). "
             "Δ = brainres − baseline per prompt. A category is a weakness when brainres is lower or tied on most of its prompts, "
             "or when a check fires more often with brainres.", "",
             "## By answer type", "",
             "| Type | n | Δ score | Δ words | brainres lower / tied / higher | Δ thinking tokens | brainres checks |",
             "|---|---:|---:|---:|---|---:|---|"]
    by_type = defaultdict(list)
    for i, v in P.items():
        by_type[v["baseline"]["type"]].append(v)
    def row(name, vs):
        ds = [v["brainres"]["score"] - v["baseline"]["score"] for v in vs]
        dw = [v["brainres"]["words"] - v["baseline"]["words"] for v in vs]
        dt = [v["brainres"].get("thinking_tokens", 0) - v["baseline"].get("thinking_tokens", 0) for v in vs]
        lo, ti, hi = sum(d < 0 for d in ds), sum(d == 0 for d in ds), sum(d > 0 for d in ds)
        ch = Counter(c for v in vs for c in v["brainres"]["checks"])
        return (f"| {name} | {len(vs)} | {st.mean(ds):+.1f} | {st.mean(dw):+.0f} | {lo} / {ti} / {hi} | {st.mean(dt):+.0f} | "
                + (", ".join(f"{k} {n}" for k, n in ch.most_common(3)) or "—") + " |"), st.mean(ds), lo, ti, hi
    scored = []
    for t, vs in sorted(by_type.items()):
        line, m, lo, ti, hi = row(t, vs)
        scored.append((m, hi - lo, t))
        lines.append(line)
    lines += ["", "## By language", "", "| Language | n | Δ score | Δ words | brainres lower / tied / higher | Δ thinking tokens | brainres checks |",
              "|---|---:|---:|---:|---|---:|---|"]
    for lang in ("en", "ko"):
        lines.append(row(lang, [v for v in P.values() if v["baseline"]["lang"] == lang])[0])
    lines += ["", "## Checks: baseline vs brainres (answers flagged)", "", "| Check | baseline | brainres |", "|---|---:|---:|"]
    cb = Counter(c for v in P.values() for c in v["baseline"]["checks"])
    cs = Counter(c for v in P.values() for c in v["brainres"]["checks"])
    for k in sorted(set(cb) | set(cs), key=lambda k: -(cb[k] + cs[k])):
        flag = " **← more with brainres**" if cs[k] > cb[k] else ""
        lines.append(f"| {k} | {cb[k]} | {cs[k]}{flag} |")
    qb = Counter(c for v in P.values() for c in v["baseline"].get("question_checks", []))
    qs = Counter(c for v in P.values() for c in v["brainres"].get("question_checks", []))
    lines += ["", "Question-aware checks (`--question`): " + (", ".join(f"{k}: baseline {qb[k]}, brainres {qs[k]}" for k in sorted(set(qb) | set(qs))) or "none fired") + "."]
    weak = [t for m, net, t in sorted(scored) if net <= 0]
    lines += ["", "## Weak categories (brainres not ahead on net)", "", (", ".join(weak) or "none") + "."]
    text = "\n".join(lines) + "\n"
    print(text)
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
