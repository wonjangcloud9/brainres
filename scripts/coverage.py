#!/usr/bin/env python3
"""coverage — is every applicable research finding actually applied in the skill?

Reads every catalog table in research/*.md whose header has `Applies` and `Situation`
columns. A finding marked Yes/Partial counts as *applied* only when its ID is cited
in a skill file (skills/**/*.md or hooks/core-card.md): `#28` for the original
catalog, `PL-03` style for domain catalogs.

Usage:
  python3 scripts/coverage.py            # summary + gaps
  python3 scripts/coverage.py --write    # also regenerate research/coverage.md
  python3 scripts/coverage.py --check    # exit 1 if coverage fell below research/.coverage-floor
"""
from __future__ import annotations

import argparse
import glob
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ID_RE = re.compile(r"^(\d{1,3}|[A-Z]{2}-\d{2,3})$")
CITE_RE = re.compile(r"(?<![\w&])#(\d{1,3})\b|\b([A-Z]{2}-\d{2,3})\b")


def parse_catalogs():
    rows = []
    for path in sorted(glob.glob(str(ROOT / "research" / "*.md"))):
        if path.endswith("coverage.md"):
            continue
        header = None
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            if not line.startswith("|"):
                header = None if not line.strip() else header
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if "Applies" in cells and "Situation" in cells:
                header = cells
                continue
            if header is None or set(line.replace("|", "").strip()) <= set("-: "):
                continue
            if len(cells) != len(header):
                continue
            rec = dict(zip(header, cells))
            rid = rec.get("#") or rec.get("ID") or ""
            if not ID_RE.match(rid):
                continue
            applies = rec["Applies"].split()[0].strip("*—-").capitalize() if rec["Applies"] else "?"
            rows.append({
                "id": rid,
                "concept": rec.get("Concept", ""),
                "ev": rec.get("Ev", ""),
                "applies": applies,
                "situation": rec["Situation"].lower(),
                "file": Path(path).name,
            })
    return rows


def cited_ids():
    files = glob.glob(str(ROOT / "skills" / "**" / "*.md"), recursive=True) + [str(ROOT / "hooks" / "core-card.md")]
    found = set()
    for f in files:
        if f.endswith("evidence.md"):
            continue  # the evidence index lists sources; it does not apply them
        for a, b in CITE_RE.findall(Path(f).read_text(encoding="utf-8")):
            found.add(a or b)
    return found


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    rows = parse_catalogs()
    cited = cited_ids()
    seen, dupes = set(), []
    for r in rows:
        if r["id"] in seen:
            dupes.append(r["id"])
        seen.add(r["id"])

    applicable = [r for r in rows if r["applies"] in ("Yes", "Partial")]
    excluded = [r for r in rows if r["applies"] not in ("Yes", "Partial")]
    applied = [r for r in applicable if r["id"] in cited]
    gaps = [r for r in applicable if r["id"] not in cited]
    pct = 100.0 * len(applied) / max(len(applicable), 1)

    by_sit = defaultdict(lambda: [0, 0])
    for r in applicable:
        by_sit[r["situation"]][1] += 1
        if r["id"] in cited:
            by_sit[r["situation"]][0] += 1

    print(f"Findings catalogued: {len(rows)}  ·  applicable: {len(applicable)}  ·  excluded with reason: {len(excluded)}")
    print(f"Applied in skill: {len(applied)}/{len(applicable)} = {pct:.1f}%")
    for s, (done, tot) in sorted(by_sit.items(), key=lambda kv: -kv[1][1]):
        print(f"  {s:<15} {done:>3}/{tot:<3}")
    if dupes:
        print(f"DUPLICATE IDs: {', '.join(sorted(set(dupes)))}")

    if a.write:
        out = ["# Coverage ledger", "",
               "Generated by `scripts/coverage.py --write`. Do not edit by hand.", "",
               f"**{len(rows)} findings catalogued · {len(applicable)} applicable · {len(excluded)} excluded with a stated reason.**", "",
               f"**Applied in the skill: {len(applied)}/{len(applicable)} ({pct:.1f}%).** A finding counts as applied only when a skill file cites its ID.", "",
               "| Situation | Applied | Applicable |", "|---|---|---|"]
        for s, (done, tot) in sorted(by_sit.items(), key=lambda kv: -kv[1][1]):
            out.append(f"| {s} | {done} | {tot} |")
        out += ["", "## Not yet applied", "", "| ID | Concept | Ev | Situation | Catalog |", "|---|---|---|---|---|"]
        out += [f"| {r['id']} | {r['concept']} | {r['ev']} | {r['situation']} | {r['file']} |" for r in gaps]
        out += ["", "## Excluded (reason in the catalog row)", "", "| ID | Concept | Ev | Catalog |", "|---|---|---|---|"]
        out += [f"| {r['id']} | {r['concept']} | {r['ev']} | {r['file']} |" for r in excluded]
        (ROOT / "research" / "coverage.md").write_text("\n".join(out) + "\n", encoding="utf-8")
        print("wrote research/coverage.md")

    if a.check:
        floor_file = ROOT / "research" / ".coverage-floor"
        floor = float(floor_file.read_text().strip()) if floor_file.exists() else 0.0
        if dupes:
            print("FAIL: duplicate finding IDs")
            return 1
        if len(applied) < floor:
            print(f"FAIL: applied findings {len(applied)} fell below floor {floor:.0f}")
            return 1
        if len(applied) > floor:
            floor_file.write_text(f"{len(applied)}\n")
            print(f"floor raised to {len(applied)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
